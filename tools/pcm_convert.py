# Convert audio -> 4-bit IMA ADPCM C array for STM32 flash playback.
# Pipeline: stereo decode -> karaoke (center cancel, removes vocals) -> 8kHz mono
#           -> loudest N-second window -> IMA ADPCM 4-bit (packed, low nibble first)
#           -> Pcm.c/h + preview wavs (buzzer-truth decode + no-karaoke A/B)
import subprocess, sys, io
import numpy as np

SRC = sys.argv[1] if len(sys.argv) > 1 else '琵琶曲dj.m4s'
CLIP = float(sys.argv[2]) if len(sys.argv) > 2 else 8.2     # seconds of OUTPUT
TEMPO = float(sys.argv[3]) if len(sys.argv) > 3 else 1.4    # playback speed multiplier
SR = 8000
FFMPEG = r'E:\ffmpeg-8.1.2-essentials_build\bin\ffmpeg.exe'

TEMPO_FILTER = ('atempo=%.2f,' % TEMPO) if abs(TEMPO - 1.0) > 0.01 else ''

def decode(filters):
    raw = subprocess.run([FFMPEG, '-v', 'error', '-i', SRC, '-af', TEMPO_FILTER + filters,
                          '-ac', '1', '-ar', str(SR), '-f', 's16le', '-'],
                         capture_output=True).stdout
    return np.frombuffer(raw, np.int16).astype(np.float32) / 32768.0

# center-cancel = (L-R)/sqrt(2): removes center-panned vocals (and bass/kick)
x_karaoke = decode('pan=mono|c0=0.707*c0-0.707*c1')
x_plain = decode('anull')
print('decoded %.1fs (tempo %.2fx, karaoke vocal-cancel applied)' % (len(x_karaoke) / SR, TEMPO))

win = int(CLIP * SR)
rms = np.sqrt(np.convolve(x_karaoke ** 2, np.ones(win), 'valid'))
start = max(10 * SR, int(np.argmax(rms)))
clip_k = x_karaoke[start:start + win].copy()
clip_p = x_plain[start:start + win].copy()
for c in (clip_k, clip_p):
    c /= (np.abs(c).max() + 1e-9) * 1 / 0.95
nf = int(0.025 * SR)
clip_k[:nf] *= np.linspace(0, 1, nf); clip_k[-nf:] *= np.linspace(1, 0, nf)
print('clip: %.1fs at %ds offset, %d ADPCM bytes' % (CLIP, start / SR, int(CLIP * SR / 2)))

# ---------------- IMA ADPCM encode (continuous stream, low nibble first) ----------------
STEP = np.array([7,8,9,10,11,12,13,14,16,17,19,21,23,25,28,31,34,37,41,45,50,55,60,66,73,80,88,97,
                 107,118,130,143,157,173,190,209,230,253,279,307,337,371,408,449,494,544,598,658,
                 724,796,876,963,1060,1166,1282,1411,1552,1707,1878,2066,2272,2499,2749,3024,3327,
                 3660,4026,4428,4871,5358,5894,6484,7132,7845,8630,9493,10442,11487,12635,13899,
                 15289,16818,18500,20350,22385,24623,27086,29794,32767])
ADJ = np.array([-1,-1,-1,-1,2,4,6,8])

def adpcm_encode(samples):
    samples = np.clip(np.round(samples * 32767), -32768, 32767).astype(np.int32)
    pred, idx = 0, 0
    nibs = []
    for s in samples:
        diff = int(s) - pred
        nib = 0 if diff >= 0 else 8
        if diff < 0: diff = -diff
        step = STEP[idx]
        delta = 0
        if diff >= step: delta |= 4; diff -= step
        if diff >= (step >> 1): delta |= 2; diff -= (step >> 1)
        if diff >= (step >> 2): delta |= 1
        nib |= delta
        # mirrored decoder update (so encoder state == decoder state)
        d2 = (step >> 3)
        if delta & 4: d2 += step
        if delta & 2: d2 += step >> 1
        if delta & 1: d2 += step >> 2
        pred += -d2 if nib & 8 else d2
        pred = max(-32768, min(32767, pred))
        idx = max(0, min(88, idx + ADJ[delta]))
        nibs.append(nib)
    n = np.array(nibs, dtype=np.uint8)
    out = np.zeros(len(nibs) // 2 + len(nibs) % 2, dtype=np.uint8)
    out[:len(n) // 2] = n[0::2] | (n[1::2] << 4)
    if len(n) % 2:
        out[-1] = n[-1]
    return out

def adpcm_decode(packed):
    pred, idx = 0, 0
    out = np.zeros(len(packed) * 2, dtype=np.float32)
    i = 0
    for b in packed:
        for nib in (b & 0x0F, b >> 4):
            step = STEP[idx]
            d = step >> 3
            if nib & 4: d += step
            if nib & 2: d += step >> 1
            if nib & 1: d += step >> 2
            pred += -d if nib & 8 else d
            pred = max(-32768, min(32767, pred))
            idx = max(0, min(88, idx + ADJ[nib & 7]))
            out[i] = pred
            i += 1
    return out / 32767.0

pcm = adpcm_encode(clip_k)
print('encoded %d bytes' % len(pcm))

# preview: DECODED ADPCM = exactly what the buzzer will output (includes quantization)
decoded = adpcm_decode(pcm)

def write_wav(sig, path):
    sig16 = np.clip(sig * 32767, -32768, 32767).astype(np.int16)
    import wave
    with wave.open(path, 'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes(sig16.tobytes())

write_wav(decoded, 'tools/pcm_preview.wav')
write_wav(clip_p, 'tools/pcm_preview_novocal_off.wav')
print('previews written')

# ---------------- Pcm.c / Pcm.h ----------------
rows = []
for i in range(0, len(pcm), 16):
    rows.append('    ' + ', '.join('%d' % v for v in pcm[i:i + 16]) + ',')
pcm_c = '''#include "Pcm.h"

// Auto-generated by tools/pcm_convert.py (%.1fs clip @ %dHz, tempo %.2fx, 4-bit IMA ADPCM, low nibble first).
// Source: %s (karaoke center-cancel applied).
const uint8_t Pcm_Audio[] = {
%s
};
const uint16_t Pcm_Len = sizeof(Pcm_Audio) / sizeof(Pcm_Audio[0]);
''' % (CLIP, SR, TEMPO, SRC.encode('ascii', 'replace').decode().replace('?', ''), '\n'.join(rows))
io.open('Stm32Link_Keil/Hardware/Pcm.c', 'w', encoding='ascii').write(pcm_c)
io.open('Stm32Link_Keil/Hardware/Pcm.h', 'w', encoding='ascii').write('''#ifndef __PCM_H
#define __PCM_H

#include "stm32f10x.h"

extern const uint8_t Pcm_Audio[];
extern const uint16_t Pcm_Len;

#endif
''')
print('Pcm.c/h written (%.1f KB)' % (len(pcm) / 1024))
