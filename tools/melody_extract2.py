# Melody extraction v2: HPSS (harmonic/percussive separation) then autocorrelation
# pitch tracking on the harmonic component. Generates:
#   tools/melody.json
#   tools/melody_preview.wav  (square-wave preview of what the buzzer will play)
#   Stm32Link_Keil/Hardware/Song.c
#   with_stm32/src/main/java/qw/with_stm32/Stm32Melody.java
import json, wave, io, os
import numpy as np
from scipy import signal, ndimage

SR, WIN, HOP = 22050, 2048, 512
FMIN, FMAX = 150.0, 1100.0
SRC = 'tools/song.wav'

with wave.open(SRC, 'rb') as w:
    data = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float64) / 32768.0

# ---- HPSS ----
f, t, Z = signal.stft(data, fs=SR, nperseg=WIN, noverlap=WIN - HOP)
mag = np.abs(Z)
Hmag = ndimage.median_filter(mag, size=(1, 17))
Pmag = ndimage.median_filter(mag, size=(17, 1))
mask = (Hmag ** 2) / (Hmag ** 2 + Pmag ** 2 + 1e-10)
_, xh = signal.istft(Z * mask, fs=SR, nperseg=WIN, noverlap=WIN - HOP)
xh = xh[:len(data)]
with wave.open('tools/song_harmonic.wav', 'wb') as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
    w.writeframes((np.clip(xh, -1, 1) * 32767).astype(np.int16).tobytes())

# ---- pitch track on harmonic component ----
size = 1 << (2 * WIN - 1).bit_length()
nfr = (len(xh) - WIN) // HOP
rms = np.zeros(nfr); midi = np.zeros(nfr); clar = np.zeros(nfr)
for i in range(nfr):
    fr = xh[i * HOP:i * HOP + WIN]
    rms[i] = np.sqrt((fr ** 2).mean())
    x = fr - fr.mean()
    X = np.fft.rfft(x, size)
    ac = np.fft.irfft(X * np.conj(X), size)[:WIN]
    if ac[0] > 1e-9:
        ac /= ac[0]
        lo, hi = int(SR / FMAX), min(int(SR / FMIN), WIN - 1)
        k = int(np.argmax(ac[lo:hi])) + lo
        a, b, c = ac[k - 1], ac[k], ac[k + 1]
        den = a - 2 * b + c
        shift = 0.5 * (a - c) / den if den != 0 else 0.0
        freq = SR / (k + shift)
        clar[i] = ac[k]
        midi[i] = 69 + 12 * np.log2(freq / 440) if freq > 0 else 0

thr = 0.10 * np.percentile(rms, 95)
voiced = (rms > thr) & (clar > 0.50) & (midi > 20)
mf = midi.copy()
for i in range(nfr):
    s = max(0, i - 2); e = min(nfr, i + 3)
    seg = midi[s:e][voiced[s:e]]
    if len(seg): mf[i] = np.median(seg)

notes = []
i = 0
while i < nfr:
    if voiced[i]:
        m0 = int(round(mf[i])); j = i
        while j < nfr and voiced[j] and int(round(mf[j])) == m0 and j - i < 200:
            j += 1
        notes.append([m0, (j - i) * HOP * 1000 / SR])
        i = j
    else:
        j = i
        while j < nfr and not voiced[j]: j += 1
        gap = (j - i) * HOP * 1000 / SR
        if gap >= 80 and notes: notes.append([0, gap])
        i = j

# legato: short rests extend previous note; merge split same-pitch notes
merged = []
for m, d in notes:
    if m == 0:
        if merged and d < 160:
            merged[-1][1] += d
        else:
            merged.append([0, d])
    else:
        if d < 80: continue
        if merged and merged[-1][0] == m and merged[-1][1] < 500:
            merged[-1][1] += d
        else:
            merged.append([m, d])

def hz(m): return 440.0 * 2 ** ((m - 69) / 12)
# merge adjacent rests and adjacent same-pitch notes
compact = []
for m, d in merged:
    if compact and compact[-1][0] == m:
        compact[-1][1] += d
    else:
        compact.append([m, d])
melody = [[m, int(round(d / 25) * 25)] for m, d in compact if d >= 70]
# trim trailing rests
while melody and melody[-1][0] == 0: melody.pop()
total = sum(d for _, d in melody)
out = [{'f': round(hz(m), 1) if m else 0, 'd': d, 'm': m} for m, d in melody]

with open('tools/melody.json', 'w', encoding='utf-8') as fp:
    json.dump(out, fp)

pitches = [m for m, d in melody if m]
rests = [d for m, d in melody if m == 0]
print('notes:', len(melody), 'pitched:', len(pitches), 'dur: %.1fs' % (total / 1000))
print('range:', min(pitches), '-', max(pitches), 'rest: %.1fs' % (sum(rests) / 1000))
u, c = np.unique(pitches, return_counts=True)
print('top:', sorted(zip(c.tolist(), u.tolist()), reverse=True)[:10])
print('first 20:', out[:20])

# ---- square-wave preview wav ----
buf = np.zeros(int(total / 1000 * SR) + SR // 4)
pos = 0
for m, d in melody:
    n = int(d / 1000 * SR)
    if m:
        freq = hz(m)
        tt = np.arange(n) / SR
        buf[pos:pos + n] += 0.35 * np.sign(np.sin(2 * np.pi * freq * tt))
    pos += n
peak = np.abs(buf).max()
if peak > 0: buf = buf / peak * 0.8
with wave.open('tools/melody_preview.wav', 'wb') as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
    w.writeframes((buf * 32767).astype(np.int16).tobytes())
print('preview written')

# ---- generate Song.c ----
rows = ',\n'.join('    {%d, %d}' % (round(o['f']) if o['m'] else 0, o['d']) for o in out)
song_c = '''#include "Song.h"

// Auto-generated by tools/melody_extract2.py (pipa-dj song, HPSS + autocorr) - do not edit.
// Each entry: {frequency in Hz (0 = rest), duration in ms}.
const uint16_t Song_Notes[][2] = {
%s
};
const uint16_t Song_Len = sizeof(Song_Notes) / sizeof(Song_Notes[0]);
''' % rows
with io.open('Stm32Link_Keil/Hardware/Song.c', 'w', encoding='ascii') as fp:
    fp.write(song_c)

# ---- generate Stm32Melody.java ----
java_rows = ',\n'.join('            {%sf, %d}' % (('0' if not o['m'] else str(o['f'])), o['d']) for o in out)
java = '''package qw.with_stm32;

// Auto-generated by tools/melody_extract2.py (pipa-dj song) - do not edit.
// {frequency in Hz (0 = rest), duration in ms}, synchronized with the STM32 Song_Notes array.
public final class Stm32Melody {
    public static final float[][] NOTES = {
%s
    };

    private Stm32Melody() {}
}
''' % java_rows
with io.open('with_stm32/src/main/java/qw/with_stm32/Stm32Melody.java', 'w', encoding='ascii') as fp:
    fp.write(java)
print('Song.c + Stm32Melody.java generated')
